import { useEffect, useMemo, useState } from 'react'
import ReactECharts from 'echarts-for-react'
import { Activity, CalendarDays, Clock3, Gauge, UsersRound } from 'lucide-react'
import { api } from '../services/api'
import type { ActivityMetrics, MetricDefinition } from '../types/api'
import { RetentionCohorts } from '../components/RetentionCohorts'
import { ConversionFunnel } from '../components/ConversionFunnel'

export function ProductAnalytics() {
  const [metrics, setMetrics] = useState<ActivityMetrics | null>(null)
  const [definitions, setDefinitions] = useState<MetricDefinition[]>([])
  const [start, setStart] = useState('')
  const [end, setEnd] = useState('')
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  async function load(nextStart?: string, nextEnd?: string) {
    setLoading(true); setError('')
    try {
      const response = await api.activityMetrics(nextStart, nextEnd)
      setMetrics(response); setStart(response.start); setEnd(response.end)
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : 'Unable to calculate activity metrics')
    } finally { setLoading(false) }
  }

  useEffect(() => {
    void load()
    api.metricDefinitions().then(setDefinitions).catch(() => setDefinitions([]))
  }, [])

  const chart = useMemo(() => ({
    backgroundColor: 'transparent',
    animationDuration: 450,
    grid: { left: 46, right: 22, top: 30, bottom: 42 },
    tooltip: { trigger: 'axis', backgroundColor: '#111a2c', borderColor: '#334155', textStyle: { color: '#e2e8f0' } },
    xAxis: { type: 'category', boundaryGap: false, data: metrics?.daily.map(point => point.period) ?? [], axisLabel: { color: '#64748b' }, axisLine: { lineStyle: { color: '#243146' } } },
    yAxis: { type: 'value', minInterval: 1, axisLabel: { color: '#64748b' }, splitLine: { lineStyle: { color: '#ffffff0a' } } },
    series: [{ name: 'Daily active users', type: 'line', smooth: true, showSymbol: false, data: metrics?.daily.map(point => point.active_users) ?? [], lineStyle: { width: 3, color: '#8EA8FF' }, areaStyle: { color: 'rgba(142,168,255,.13)' } }],
  }), [metrics])

  const cards = metrics ? [
    { label: 'Latest DAU', value: formatNumber(metrics.summary.latest_dau), note: 'Active on latest observed day', icon: <Activity size={17}/> },
    { label: 'Latest WAU', value: formatNumber(metrics.summary.latest_wau), note: 'Monday–Sunday calendar week', icon: <UsersRound size={17}/> },
    { label: 'Latest MAU', value: formatNumber(metrics.summary.latest_mau), note: 'UTC calendar month', icon: <CalendarDays size={17}/> },
    { label: 'DAU / MAU', value: metrics.summary.dau_mau_ratio == null ? '—' : `${(metrics.summary.dau_mau_ratio * 100).toFixed(1)}%`, note: 'Daily engagement ratio', icon: <Gauge size={17}/> },
    { label: 'Sessions / user', value: formatDecimal(metrics.summary.sessions_per_user), note: 'Within selected date range', icon: <UsersRound size={17}/> },
    { label: 'Avg. session', value: formatDuration(metrics.summary.average_session_duration_seconds), note: 'Completed sessions only', icon: <Clock3 size={17}/> },
  ] : []

  return <main className="mx-auto max-w-7xl px-6 py-10 lg:px-10">
    <div className="flex flex-col justify-between gap-5 lg:flex-row lg:items-end">
      <section><div className="mb-3 text-xs font-semibold uppercase tracking-[0.18em] text-accent">Product analytics</div><h1 className="text-3xl font-semibold tracking-tight">Engagement, with a written definition.</h1><p className="mt-3 max-w-2xl text-sm leading-6 text-slate-400">These metrics are computed by deterministic SQL—not generated by a language model. Activity uses UTC calendar periods.</p></section>
      <div className="flex flex-wrap items-end gap-2 rounded-xl border border-white/[0.08] bg-panel p-3">
        <label className="text-[11px] uppercase tracking-wider text-slate-500">From<input aria-label="Start date" type="date" value={start} onChange={event => setStart(event.target.value)} className="mt-1 block rounded-lg border border-white/10 bg-ink px-3 py-2 text-sm normal-case tracking-normal text-slate-200 [color-scheme:dark]"/></label>
        <label className="text-[11px] uppercase tracking-wider text-slate-500">To<input aria-label="End date" type="date" value={end} onChange={event => setEnd(event.target.value)} className="mt-1 block rounded-lg border border-white/10 bg-ink px-3 py-2 text-sm normal-case tracking-normal text-slate-200 [color-scheme:dark]"/></label>
        <button disabled={loading || !start || !end} onClick={() => void load(start, end)} className="rounded-lg bg-accent px-4 py-2 text-sm font-semibold text-ink disabled:opacity-40">Apply</button>
      </div>
    </div>

    {error && <div role="alert" className="mt-7 rounded-xl border border-amber-400/20 bg-amber-400/[0.06] p-4 text-sm text-amber-100"><div className="font-medium">This database is not ready for canonical activity metrics.</div><div className="mt-1 text-amber-100/70">{error}</div></div>}
    {loading && !metrics && <div className="mt-8 h-64 animate-pulse rounded-2xl bg-white/[0.025]"/>}
    <RetentionCohorts/>
    <ConversionFunnel/>
    {metrics && <>
      <div className="mt-8 grid gap-3 sm:grid-cols-2 xl:grid-cols-3">{cards.map(card => <div key={card.label} className="rounded-2xl border border-white/[0.08] bg-panel p-5"><div className="flex items-center justify-between text-sm text-slate-500"><span>{card.label}</span><span className="text-accent">{card.icon}</span></div><div className="mt-3 text-3xl font-semibold tracking-tight text-slate-50">{card.value}</div><div className="mt-2 text-xs text-slate-600">{card.note}</div></div>)}</div>
      <section className="mt-5 rounded-2xl border border-white/[0.08] bg-panel p-5"><div className="flex flex-wrap items-end justify-between gap-3"><div><h2 className="font-medium">Daily active users</h2><p className="mt-1 text-xs text-slate-500">Distinct users with at least one event per UTC day</p></div><span className="text-xs text-slate-600">Data available {metrics.data_start} → {metrics.data_through}</span></div><ReactECharts option={chart} style={{height: 330}}/></section>
      <section className="mt-5 rounded-2xl border border-white/[0.08] bg-panel p-5"><h2 className="font-medium">Metric contract</h2><p className="mt-1 text-xs text-slate-500">Auditable formulas used by the API and dashboard.</p><div className="mt-4 divide-y divide-white/[0.06]">{definitions.map(definition => <details key={definition.key} className="group py-3"><summary className="cursor-pointer list-none text-sm text-slate-200">{definition.name}<span className="ml-2 text-xs text-slate-600 group-open:text-accent">view definition</span></summary><p className="mt-2 text-xs leading-5 text-slate-400">{definition.description}</p><code className="mt-2 block rounded-lg bg-ink px-3 py-2 text-xs text-accent">{definition.formula}</code><div className="mt-2 text-[11px] text-slate-600">Requires {definition.required_fields.join(', ')}</div></details>)}</div></section>
    </>}
  </main>
}

function formatNumber(value: number) { return new Intl.NumberFormat().format(value) }
function formatDecimal(value: number | null) { return value == null ? '—' : value.toFixed(2) }
function formatDuration(value: number | null) {
  if (value == null) return '—'
  if (value < 60) return `${Math.round(value)} sec`
  return `${Math.floor(value / 60)}m ${Math.round(value % 60)}s`
}
